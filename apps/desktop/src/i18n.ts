export function translate(language: Language, key: TranslationKey): string {
  return language === "tr" ? turkish[key] : english[key];
}

export function errorKey(error: unknown): TranslationKey {
  return typeof error === "string" && Object.hasOwn(english, error)
    ? error as TranslationKey : "unknownError";
}

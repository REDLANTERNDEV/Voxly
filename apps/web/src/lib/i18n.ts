export type TranslationKey = keyof typeof translations.en;

/**
 * Hooks below the interface report failures as keys rather than sentences, so
 * the words are chosen where the language is known instead of being fixed in
 * English at the point the failure happens.
 */
export type VoiceErrorKey = Extract<TranslationKey, `voiceError.${string}`>;
export type AudioErrorKey = Extract<TranslationKey, `audioError.${string}`>;

export function detectLanguage(languages: readonly string[] = getNavigatorLanguages()): LanguageCode {
  for (const language of languages) {
    const normalized = language.toLowerCase();
    if (normalized === "tr" || normalized.startsWith("tr-")) {
      return "tr";
    }
    if (normalized === "en" || normalized.startsWith("en-")) {
      return "en";
    }
  }

  return "en";
}

export function resolveLanguageChoice(savedLanguage: string | null, browserLanguages: readonly string[] = getNavigatorLanguages()): LanguageCode {
  return isLanguageCode(savedLanguage) ? savedLanguage : detectLanguage(browserLanguages);
}

export function readLanguageChoice(): LanguageCode {
  try {
    return resolveLanguageChoice(localStorage.getItem(languageStorageKey));
  } catch {
    return detectLanguage();
  }
}

export function saveLanguageChoice(language: LanguageCode) {
  try {
    localStorage.setItem(languageStorageKey, language);
  } catch {
    return;
  }
}

export function translate(language: LanguageCode, key: TranslationKey, values?: Record<string, string | number>) {
  let value: string = translations[language][key] ?? translations.en[key];
  if (!values) {
    return value;
  }

  for (const [name, replacement] of Object.entries(values)) {
    value = value.replaceAll(`{${name}}`, String(replacement));
  }

  return value;
}

export function languageLabel(language: LanguageCode) {
  return language === "tr" ? "Türkçe" : "English";
}

function isLanguageCode(value: string | null): value is LanguageCode {
  return Boolean(value && supportedLanguages.has(value as LanguageCode));
}

function getNavigatorLanguages() {
  return typeof navigator === "undefined" ? [] : navigator.languages;
}
